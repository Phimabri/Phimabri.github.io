let lang = 'en';
try {
  lang = localStorage.getItem('lang') || ((navigator.language || 'en').toLowerCase().startsWith('fr') ? 'fr' : 'en');
} catch {
  lang = (navigator.language || 'en').toLowerCase().startsWith('fr') ? 'fr' : 'en';
}

export const t = (k) => DICT[lang][k] ?? DICT.en[k] ?? k;
export const getLang = () => lang;

export function applyLang(next = lang) {
  lang = next;
  try { localStorage.setItem('lang', lang); } catch {}
  document.documentElement.lang = lang;
  document.title = t('meta.title');
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => el.setAttribute('aria-label', t(el.dataset.i18nAria)));
}
